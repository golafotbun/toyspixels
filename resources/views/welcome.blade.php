        // Filter All Products (3 Jendela: Semua, Mainan, Technology)
        function filterAllProducts(group, e) {
            if (e && e.preventDefault) {
                e.preventDefault();
            }

            try {
                if (typeof playArcadeBeep === 'function') {
                    playArcadeBeep(520, 0.06, 'sine');
                }
            } catch (err) {
                // Ignore audio errors
            }

            const target = String(group || 'semua').toLowerCase().trim();
            const items = document.querySelectorAll('.product-item');
            const btns = document.querySelectorAll('.prod-filter-btn');

            // 1. Update status tombol filter (Semua, Mainan, Technology)
            btns.forEach(b => {
                const bFilter = (b.getAttribute('data-filter') || '').toLowerCase().trim();
                const isActive = (bFilter === target) ||
                                 ((target === 'semua' || target === 'all') && (bFilter === 'semua' || bFilter === 'all')) ||
                                 ((target === 'technology' || target === 'teknologi') && (bFilter === 'technology' || bFilter === 'teknologi'));

                if (isActive) {
                    b.classList.add('bg-[#0B1A30]', 'text-white', 'shadow-sm');
                    b.classList.remove('bg-white', 'text-slate-700');
                } else {
                    b.classList.remove('bg-[#0B1A30]', 'text-white', 'shadow-sm');
                    b.classList.add('bg-white', 'text-slate-700');
                }
            });

            // 2. Filter item produk berdasarkan tag artikel
            items.forEach(item => {
                const rawTags = (item.getAttribute('data-tags') || '').toLowerCase();
                const tagList = rawTags.split(/[\s,]+/).filter(Boolean);
                const itemGroup = (item.getAttribute('data-group') || '').toLowerCase();

                let shouldShow = false;

                if (target === 'semua' || target === 'all') {
                    // Pilihan Semua: Memunculkan semua artikel yang memiliki tag semua
                    shouldShow = tagList.includes('semua') || tagList.includes('all') || tagList.length === 0;
                } else if (target === 'mainan') {
                    // Pilihan Mainan: Memunculkan artikel khusus yang memiliki tag mainan
                    shouldShow = tagList.includes('mainan') || itemGroup === 'mainan';
                } else if (target === 'technology' || target === 'teknologi') {
                    // Pilihan Technology: Memunculkan artikel khusus yang memiliki tag technology
                    shouldShow = tagList.includes('technology') || tagList.includes('teknologi') || itemGroup === 'technology';
                } else {
                    shouldShow = tagList.includes(target) || itemGroup === target;
                }

                if (shouldShow) {
                    item.classList.remove('hidden');
                    item.style.setProperty('display', 'flex', 'important');
                } else {
                    item.classList.add('hidden');
                    item.style.setProperty('display', 'none', 'important');
                }
            });

            // 3. Toggle CTA button dan category links di bawah etalase
            const ctaAll = document.getElementById('catalogCtaAll');
