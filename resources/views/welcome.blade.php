        // ==============================================================
        // TAHAP 3: TOP TOYS HORIZONTAL SLIDER ENGINE (PERSIS TAHAP 3.PNG)
        // 3 Cards 100% visible, 4th card gradient fade, Prev/Next navigation
        // ==============================================================
        (function initTopToysSlider() {
            const track = document.getElementById('topToysTrack');
            const prevBtn = document.getElementById('topToysPrevBtn');
            const nextBtn = document.getElementById('topToysNextBtn');
            const cards = Array.from(document.querySelectorAll('.top-toy-card'));
            if (!track || !cards.length) return;

            let currentIndex = 0;
            const total = cards.length;

            function getVisibleCount() {
                const width = window.innerWidth;
                if (width < 768) return 1;
                if (width < 1024) return 2;
                return 3;
            }

            function updateSlider() {
                const visibleCount = getVisibleCount();
                const maxIndex = Math.max(0, total - visibleCount);
                if (currentIndex > maxIndex) currentIndex = maxIndex;
                if (currentIndex < 0) currentIndex = 0;

                const firstCard = cards[0];
                const cardWidth = firstCard.offsetWidth;
                const gap = 24; // 1.5rem (gap-6)
                const step = cardWidth + gap;

                track.style.transform = `translateX(-${currentIndex * step}px)`;

                // Opacity management: 3 visible cards 100% opacity, card #4 gradasi/fade
                cards.forEach((card, idx) => {
                    const relPos = idx - currentIndex;
                    if (relPos >= 0 && relPos < visibleCount) {
                        // 100% visible
                        card.style.opacity = '1';
                        card.style.filter = 'none';
                        card.style.pointerEvents = 'auto';
                    } else if (relPos === visibleCount) {
                        // No 4: gradasi / soft fade (diperhalus bersama gradient mask container)
                        card.style.opacity = '0.55';
                        card.style.filter = 'none';
                        card.style.pointerEvents = 'auto';
                    } else {
                        card.style.opacity = '0.2';
                        card.style.pointerEvents = 'none';
                    }
                });

                // Update prev/next button states
                if (prevBtn) {
                    prevBtn.disabled = (currentIndex === 0);
                    prevBtn.style.opacity = currentIndex === 0 ? '0.35' : '1';
                    prevBtn.style.cursor = currentIndex === 0 ? 'not-allowed' : 'pointer';
                }
                if (nextBtn) {
                    nextBtn.disabled = (currentIndex >= maxIndex);
                    nextBtn.style.opacity = currentIndex >= maxIndex ? '0.35' : '1';
                    nextBtn.style.cursor = currentIndex >= maxIndex ? 'not-allowed' : 'pointer';
                }
            }

            if (nextBtn) {
                nextBtn.addEventListener('click', () => {
                    const visibleCount = getVisibleCount();
                    const maxIndex = Math.max(0, total - visibleCount);
                    if (currentIndex < maxIndex) {
                        currentIndex++;
                        updateSlider();
                    }
                });
            }

            if (prevBtn) {
                prevBtn.addEventListener('click', () => {
                    if (currentIndex > 0) {
                        currentIndex--;
                        updateSlider();
                    }
                });
            }

            window.addEventListener('resize', updateSlider);

            // Touch swipe support
            let startX = 0;
            let isDragging = false;
            track.addEventListener('touchstart', (e) => {
                startX = e.touches[0].clientX;
                isDragging = true;
            }, { passive: true });

            track.addEventListener('touchend', (e) => {
                if (!isDragging) return;
                const endX = e.changedTouches[0].clientX;
                const diff = endX - startX;
                const visibleCount = getVisibleCount();
                const maxIndex = Math.max(0, total - visibleCount);
                if (diff < -40 && currentIndex < maxIndex) {
                    currentIndex++;
                    updateSlider();
                } else if (diff > 40 && currentIndex > 0) {
                    currentIndex--;
                    updateSlider();
                }
                isDragging = false;
            });

            // Initial render
            setTimeout(updateSlider, 50);
        })();

        // ==============================================================
        // 3D ARC SLIDER ENGINE (PERSIS REFERENSI TAHAP 2.PNG)
        // Autoplay, 3D Arc Curvature, Next/Prev, Touch & Mouse Drag
        // ==============================================================
        (function initArcSlider() {
            const cards = Array.from(document.querySelectorAll('.arc-card'));
            const prevBtn = document.getElementById('arcPrevBtn');
            const nextBtn = document.getElementById('arcNextBtn');
            const dotsContainer = document.getElementById('arcDots');
            const container = document.getElementById('arcCarouselContainer');
            if (!cards.length) return;

            let currentIndex = 0;
            const total = cards.length;
            let autoplayTimer = null;
            let isDragging = false;
            let startX = 0;

            function getResponsiveConfig() {
                const width = window.innerWidth;
                if (width < 480) return { spacing: 114, centerGap: 10 };
                if (width < 768) return { spacing: 132, centerGap: 12 };
                if (width < 1024) return { spacing: 154, centerGap: 14 };
                if (width < 1280) return { spacing: 180, centerGap: 16 };
                return { spacing: 196, centerGap: 20 };
            }

            function updateArcSlider() {
                const { spacing, centerGap } = getResponsiveConfig();
                const isMobile = window.innerWidth < 768;

                cards.forEach((card, index) => {
                    // Circular distance in loop for 12 cards
                    let diff = (index - currentIndex) % total;
                    if (diff > Math.floor(total / 2)) diff -= total;
                    if (diff < -Math.floor(total / 2)) diff += total;

                    // Exactly 6 square cards visible in the arc: diff in [-2, -1, 0, 1, 2, 3]
                    const isVisibleInArc = (diff >= -2 && diff <= 3);

                    if (!isVisibleInArc) {
                        card.style.opacity = '0';
                        card.style.pointerEvents = 'none';
                        const exitRank = diff < -2 ? -3.5 : 3.5;
                        const exitOffset = exitRank > 0 ? (centerGap / 2) : (-centerGap / 2);
                        const exitX = exitRank * spacing + exitOffset;
                        card.style.transform = `translateX(${exitX}px) translateY(55px) rotateY(${exitRank * 11}deg) scale(0.68)`;
                        card.style.zIndex = '1';
                        return;
                    }

                    // Symmetrical rank: [-2.5, -1.5, -0.5, 0.5, 1.5, 2.5]
                    const rank = diff - 0.5;
                    const absRank = Math.abs(rank);

                    // Horizontal offset with extra center spacing so middle cards never touch
                    const centerOffset = rank > 0 ? (centerGap / 2) : (-centerGap / 2);
                    const x = rank * spacing + centerOffset;

                    // Parabolic arc curve: center pair highest, sides dip down smoothly
                    const y = Math.pow(absRank, 2) * (isMobile ? 3.8 : 5.2);
                    // Rotation around Y axis creates cylindrical curvature towards viewer
                    const rotateY = rank * (isMobile ? 8.5 : 8.0);
                    // Perspective scale
                    const scale = Math.max(0.78, 1 - (absRank - 0.5) * 0.08);
                    // Depth z-index
                    const zIndex = Math.round(50 - absRank * 8);
                    // Opacity
                    const opacity = Math.max(0.82, 1 - (absRank - 0.5) * 0.08);

                    card.style.transform = `translateX(${x}px) translateY(${y}px) rotateY(${rotateY}deg) scale(${scale})`;
                    card.style.zIndex = zIndex;
                    card.style.opacity = opacity;
                    card.style.pointerEvents = 'auto';
                });

                // Update dots
                if (dotsContainer) {
                    const dots = dotsContainer.querySelectorAll('.arc-dot');
                    dots.forEach((dot, idx) => {
                        if (idx === currentIndex) {
                            dot.className = 'arc-dot h-2 w-6 rounded-full bg-[#E3FF73] transition-all duration-300 shadow-sm';
                        } else {
                            dot.className = 'arc-dot h-2 w-2 rounded-full bg-white/40 hover:bg-white/70 transition-all duration-300';
                        }
                    });
                }
            }

            function goToSlide(index) {
                currentIndex = (index + total) % total;
                updateArcSlider();
            }

            function nextSlide() {
                goToSlide(currentIndex + 1);
            }

            function prevSlide() {
                goToSlide(currentIndex - 1);
            }

            if (nextBtn) nextBtn.addEventListener('click', () => { nextSlide(); resetAutoplay(); });
            if (prevBtn) prevBtn.addEventListener('click', () => { prevSlide(); resetAutoplay(); });

            // Click card to bring it to center
            cards.forEach((card, idx) => {
                card.addEventListener('click', () => {
                    if (idx !== currentIndex) {
                        goToSlide(idx);
                        resetAutoplay();
                    }
                });
            });

            // Create indicator dots
            if (dotsContainer) {
                dotsContainer.innerHTML = '';
                cards.forEach((_, idx) => {
                    const dot = document.createElement('button');
                    dot.type = 'button';
                    dot.className = `arc-dot h-2 rounded-full transition-all duration-300 ${idx === 0 ? 'w-6 bg-[#E3FF73]' : 'w-2 bg-white/40'}`;
                    dot.setAttribute('aria-label', `Slide ${idx + 1}`);
                    dot.addEventListener('click', () => {
                        goToSlide(idx);
                        resetAutoplay();
                    });
                    dotsContainer.appendChild(dot);
                });
            }

            // Autoplay management (Dipercepat menjadi 1.6 detik per slide)
            function startAutoplay() {
                stopAutoplay();
                autoplayTimer = setInterval(nextSlide, 1600);
            }

            function stopAutoplay() {
                if (autoplayTimer) clearInterval(autoplayTimer);
            }

            function resetAutoplay() {
                stopAutoplay();
                startAutoplay();
            }

            if (container) {
                container.addEventListener('mouseenter', stopAutoplay);
                container.addEventListener('mouseleave', startAutoplay);

                // Touch swipe
                container.addEventListener('touchstart', (e) => {
                    stopAutoplay();
                    startX = e.touches[0].clientX;
                    isDragging = true;
                }, { passive: true });

                container.addEventListener('touchend', (e) => {
                    if (!isDragging) return;
                    const endX = e.changedTouches[0].clientX;
                    const diff = endX - startX;
                    if (diff > 40) {
                        prevSlide();
                    } else if (diff < -40) {
                        nextSlide();
                    }
                    isDragging = false;
                    startAutoplay();
                });

                // Mouse drag
                container.addEventListener('mousedown', (e) => {
                    // Only start drag if not clicking a link or button
                    if (e.target.closest('a') || e.target.closest('button')) return;
                    stopAutoplay();
                    startX = e.clientX;
                    isDragging = true;
                });

                window.addEventListener('mouseup', (e) => {
                    if (!isDragging) return;
                    const diff = e.clientX - startX;
                    if (diff > 50) {
                        prevSlide();
                    } else if (diff < -50) {
                        nextSlide();
                    }
                    isDragging = false;
                    startAutoplay();
                });
            }

            window.addEventListener('resize', updateArcSlider);

            // Initialize on DOM ready
            updateArcSlider();
            startAutoplay();
        })();
    </script>
